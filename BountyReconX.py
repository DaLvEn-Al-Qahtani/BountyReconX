COMMON_PATHS = [
"admin","administrator","admin/login","dashboard","panel","cpanel",
"login","signin","signup","api","api/v1","api/v2","graphql",
"swagger","swagger-ui","v3/api-docs",
"dev","test","staging","debug",
".git",".git/config",".env","config.php",
"backup","backup.zip","db.sql",
"robots.txt","sitemap.xml",
"wp-admin","wp-login.php",
"uploads","files","private"
]

KEYWORDS = ["api","token","secret","key","auth","debug","admin"]
JS_REGEX = r"https?://[^\s\"']+|\/[a-zA-Z0-9_\-\/]+"
SEC_HEADERS = [
"Content-Security-Policy",
"X-Frame-Options",
"X-Content-Type-Options",
"Strict-Transport-Security"
]
TIMEOUT = aiohttp.ClientTimeout(total=8)

# ================== RECON CLASS ==================
class Recon:
    def __init__(self, url, threads, depth):
        self.base = url.rstrip("/")
        self.domain = urlparse(self.base).netloc
        self.sem = asyncio.Semaphore(threads)
        self.depth = depth
        self.visited = set()
        self.results = {
            "paths": [],
            "js": [],
            "endpoints": [],
            "params": [],
            "keywords": [],
            "top10": [],
            "sensitive": []
        }

    async def fetch(self, session, url, method="GET"):
        try:
            async with self.sem:
                async with session.request(method, url, timeout=TIMEOUT, allow_redirects=False) as r:
                    text = await r.text(errors="ignore")
                    return r.status, text, r.headers
        except:
            return None, None, None

    # ---------- PATH SCAN ----------
    async def path_scan(self, session):
        print(Fore.YELLOW + "[*] Path Discovery")
        tasks = [self.check_path(session, p) for p in COMMON_PATHS]
        await asyncio.gather(*tasks)

    async def check_path(self, session, path):
        url = f"{self.base}/{path}"
        status, _, _ = await self.fetch(session, url, "HEAD")
        if status and status not in [404]:
            self.results["paths"].append((url, status))
            print(Fore.GREEN + f"[+] {url} ({status})")

    # ---------- CRAWLER ----------
    async def crawl(self, session, url, level=0):
        if level > self.depth or url in self.visited:
            return
        self.visited.add(url)

        _, text, _ = await self.fetch(session, url)
        if not text:
            return

        soup = BeautifulSoup(text, "html.parser")

        # Links
        for a in soup.find_all("a", href=True):
            link = urljoin(url, a["href"])
            if self.domain in link:
                await self.crawl(session, link, level + 1)

        # Scripts
        for s in soup.find_all("script", src=True):
            js = urljoin(url, s["src"])
            if js not in self.results["js"]:
                self.results["js"].append(js)

        # Params
        parsed = urlparse(url)
        if parsed.query:
            self.results["params"].append((url, list(parse_qs(parsed.query))))

        # Keywords
        for k in KEYWORDS:
            if k in text.lower():
                self.results["keywords"].append((url, k))

    # ---------- JS ANALYSIS ----------
    async def analyze_js(self, session):
        print(Fore.YELLOW + "[*] JavaScript Analysis")
        for js in self.results["js"]:
            _, text, _ = await self.fetch(session, js)
            if not text:
                continue
            for ep in set(re.findall(JS_REGEX, text)):
                if ep.startswith("/"):
                    self.results["endpoints"].append((js, ep))
                    print(Fore.CYAN + f"[JS] {ep}")

    # ---------- TOP 10 INDICATORS ----------
    async def top10_checks(self, session):
        print(Fore.YELLOW + "[*] OWASP Top 10 Indicators")
        _, text, headers = await self.fetch(session, self.base)
        if not headers:
            return

        # Missing headers
        for h in SEC_HEADERS:
            if h not in headers:
                self.results["top10"].append(f"Missing Header: {h}")

        # XSS reflection
        test = "<xss>"
        _, body, _ = await self.fetch(session, self.base + "?q=" + test)
        if body and test in body:
            self.results["top10"].append("XSS Reflection Indicator")

        # CORS wildcard
        if headers.get("Access-Control-Allow-Origin") == "*":
            self.results["top10"].append("CORS Wildcard (*)")

        # Tokens in page
        if text and re.search(r"(token|api_key|secret)", text, re.I):
            self.results["top10"].append("Sensitive Token Keyword")

    # ---------- SENSITIVE FILES ----------
    async def sensitive_files(self, session):
        print(Fore.YELLOW + "[*] Checking Sensitive Files")
        sensitive_paths = [".env", ".git/config", "backup.zip", "db.sql", "config.php"]
        tasks = [self.check_path(session, p) for p in sensitive_paths]
        await asyncio.gather(*tasks)
        for url, status in self.results["paths"]:
            if any(f in url for f in sensitive_paths):
                self.results["sensitive"].append((url, status))

# ================= MAIN =================
async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-u","--url", required=True)
    parser.add_argument("--paths", action="store_true")
    parser.add_argument("--crawl", action="store_true")
    parser.add_argument("--js", action="store_true")
    parser.add_argument("--top10", action="store_true")
    parser.add_argument("--sensitive", action="store_true")
    parser.add_argument("--all", action="store_true", help="Run all modules")
    parser.add_argument("--threads", type=int, default=100)
    parser.add_argument("--depth", type=int, default=2)
    args = parser.parse_args()

    banner()
    recon = Recon(args.url, args.threads, args.depth)

    async with aiohttp.ClientSession() as session:
        run_all = args.all
        if args.paths or run_all:
            await recon.path_scan(session)
        if args.crawl or run_all:
            await recon.crawl(session, recon.base)
        if args.js or run_all:
            await recon.analyze_js(session)
        if args.top10 or run_all:
            await recon.top10_checks(session)
        if args.sensitive or run_all:
            await recon.sensitive_files(session)

    print(Fore.MAGENTA + "\n====== SUMMARY ======")
    for k,v in recon.results.items():
        print(Fore.WHITE + f"{k.upper()}: {len(v)}")

    # Save JSON + TXT automatically
    save = input(Fore.YELLOW + "\nDo you want to save results? [y/N]: ").strip().lower()
    if save == "y":
        domain = urlparse(args.url).netloc
        json_file = f"BountyReconX_{domain}.json"
        txt_file = f"BountyReconX_{domain}.txt"
        with open(json_file,"w") as f:
            json.dump(recon.results,f,indent=2)
        with open(txt_file,"w") as f:
            for k,v in recon.results.items():
                f.write(f"{k.upper()}:\n")
                for item in v:
                    f.write(f"{item}\n")
                f.write("\n")
        print(Fore.GREEN + f"[+] Results saved to {json_file} and {txt_file}")

if __name__ == "__main__":
    asyncio.run(main())
